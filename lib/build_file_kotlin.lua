--- The `.gradle.kts` a project carrying Kotlin build logic is built from: a
--- wrapper over today's Groovy render rather than a second renderer (spec 7.2).
--- Type-safe accessors exist only in the script whose `plugins {}` applied the
--- plugin, so the carried text has to sit in this file, beside that block.
local build_file_kotlin = {}

local HEADER = "// Generated by daukle/gradle. Do not edit: daukle.toml and the carried file are"
               .. " yours, this is not.\n"

local function quoted(text)
  local escaped = string.gsub(text, "\\", "\\\\")
  escaped = string.gsub(escaped, '"', '\\"')
  escaped = string.gsub(escaped, "%$", "\\$")
  return '"' .. escaped .. '"'
end

local function is_lifted_line(line)
  return string.match(line, "^%s*$") ~= nil
         or string.match(line, "^%s*//") ~= nil
         or string.match(line, "^%s*import%s") ~= nil
end

--- The carried text split before its first statement that is not an import,
--- both halves verbatim.
---
--- @implNote Kotlin takes an import only ahead of every other statement, so the
--- wrapper's own blocks would end the import list (spec 7.2). A script that
--- compiled already has its imports first, which is why a split on leading
--- import, comment and blank lines finds them without parsing anything.
local function split_imports(text)
  local offset = 1
  while offset <= #text do
    local line_end = string.find(text, "\n", offset, true) or #text
    if not is_lifted_line(string.sub(text, offset, line_end)) then break end
    offset = line_end + 1
  end
  return string.sub(text, 1, offset - 1), string.sub(text, offset)
end

local function plugins_block(ids)
  if #ids == 0 then return "" end
  local lines = { "plugins {" }
  for index = 1, #ids do lines[#lines + 1] = "  id(" .. quoted(ids[index]) .. ")" end
  lines[#lines + 1] = "}"
  return table.concat(lines, "\n") .. "\n\n"
end

--- @param ids every plugin id the project applies, each named without a
--- version: the jar is on the settings classpath or built into Gradle
--- @param rendered the Groovy render's path from the build's root project
--- @implNote `apply(from = ...)` resolves against the PROJECT's directory, and
--- a module's is its real one, so the path goes through `rootProject.file`:
--- measured on 7.6.4 and 9.6.0 in a root and a module.
function build_file_kotlin.wrapper(ids, rendered, carried_text)
  local imports, rest = split_imports(carried_text)
  if imports ~= "" and string.sub(imports, -1) ~= "\n" then imports = imports .. "\n" end
  return HEADER .. imports .. plugins_block(ids)
         .. "apply(from = rootProject.file(" .. quoted(rendered) .. "))\n\n" .. rest
end

return build_file_kotlin
