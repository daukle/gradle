--- The settings files Gradle reads: the outer settings.gradle, the settings
--- plugins script it applies, and each included build's own settings.gradle.
local settings_file = {}

local build_file = daukle.require("lib/build_file")
local composite = daukle.require("lib/composite")
local groovy = daukle.require("lib/groovy")
local carried = daukle.require("lib/carried")
local catalogs = daukle.require("lib/catalogs")
local verbatim = daukle.require("lib/verbatim")
local build_file_kotlin = daukle.require("lib/build_file_kotlin")

settings_file.SCRIPT = carried.SETTINGS_PLUGINS

--- The carried settings code, after everything the settings render declares,
--- so a hook it registers is in place before any project evaluates (spec
--- D-187, 4.3); empty for none.
--- @param checked what `verbatim.checked` returned, or nil
local function carried_settings_text(checked)
  if checked == nil then return "" end
  return "\n" .. verbatim.warn_line(checked) .. "\n" .. checked.text
end

--[[ Resolves an id the way Gradle does, through the jar's own descriptor, but
     against THIS script's classloader: `apply plugin: '<id>'` from an applied
     script looks the id up on the target's classloader and fails with "Plugin
     with id ... not found", measured on 8.13 and 9.6.0. ]]
local APPLY_BY_ID = {
  "def daukleApply = { String id ->",
  "  def descriptor = buildscript.classLoader"
    .. ".getResource(\"META-INF/gradle-plugins/${id}.properties\")",
  "  if (descriptor == null) {",
  "    throw new GradleException(\"no plugin descriptor for \" + id"
    .. " + \" on the settings classpath\")",
  "  }",
  "  def properties = new Properties()",
  "  descriptor.withInputStream { properties.load(it) }",
  "  apply plugin: buildscript.classLoader"
    .. ".loadClass(properties.getProperty('implementation-class'))",
  "}",
}

--- The script settings.gradle applies when the manifest declares settings
--- plugins: the pinned classpath, then every apply, then the configure blocks.
---
--- @implNote a task writes it rather than generate, because generate may not
--- acquire a jar, and settings.gradle stays generate's own: a task rewriting
--- that file would make every later sync report it as changed outside daukle.
--- @implNote the order is load-bearing: a configure block naming a plugin's
--- extension fails before that plugin applied.
function settings_file.settings_plugins(jars, plugins, configure)
  local lines = { "// Generated by daukle/gradle. Do not edit." }
  if #jars > 0 then
    lines[#lines + 1] = ""
    lines[#lines + 1] = "buildscript {"
    lines[#lines + 1] = "  dependencies {"
    lines[#lines + 1] = "    classpath files(\n" .. build_file.file_list(jars, "      ") .. "\n    )"
    lines[#lines + 1] = "  }"
    lines[#lines + 1] = "}"
  end
  if #plugins > 0 then
    lines[#lines + 1] = ""
    for index = 1, #APPLY_BY_ID do lines[#lines + 1] = APPLY_BY_ID[index] end
    lines[#lines + 1] = ""
    for index = 1, #plugins do
      lines[#lines + 1] = "daukleApply(" .. groovy.quoted(plugins[index].id) .. ")"
    end
  end
  local configuration = build_file.configuration(configure, nil, "settingsConfigure")
  if #configuration > 0 then
    lines[#lines + 1] = ""
    for index = 1, #configuration do lines[#lines + 1] = configuration[index] end
  end
  return table.concat(lines, "\n") .. "\n"
end

function settings_file.included_settings(gradle_name)
  return "// Generated by daukle/gradle. Do not edit.\nrootProject.name = "
         .. groovy.quoted(gradle_name) .. "\n"
end

local function include_build_line(name)
  return "includeBuild(" .. groovy.quoted(composite.path_of(name)) .. ")"
end

local function append_plugin_management(lines, composite_record)
  if composite_record == nil then return end
  if #composite_record.plugin_builds > 0 then
    lines[#lines + 1] = "pluginManagement {"
    for _, build_name in ipairs(composite_record.plugin_builds) do
      lines[#lines + 1] = "  " .. include_build_line(build_name)
    end
    lines[#lines + 1] = "}"
  end
end

local function append_settings_plugins_block(lines, composite_record)
  if composite_record == nil then return end
  if #composite_record.settings_ids > 0 then
    for _, line in ipairs(composite.plugins_block(composite_record.settings_ids)) do
      lines[#lines + 1] = line
    end
  end
end

--- @implNote reads a list a task writes because generate may not acquire the
--- jars it names; `buildscript {}` stays after `pluginManagement {}` and ahead
--- of `plugins {}`, the order Gradle requires of a settings script. A missing
--- list, which a discovery's bare baseline leaves, is an empty classpath.
local function append_settings_classpath(lines, classpath_file)
  if classpath_file == nil then return end
  lines[#lines + 1] = "buildscript {"
  lines[#lines + 1] = "  dependencies {"
  lines[#lines + 1] = "    classpath files(file(" .. groovy.quoted(classpath_file) .. ").with {"
  lines[#lines + 1] = "      it.exists() ? it.readLines().findAll { it } : []"
  lines[#lines + 1] = "    })"
  lines[#lines + 1] = "  }"
  lines[#lines + 1] = "}"
end

local function climb_of(name)
  local _, separators = string.gsub(name, "/", "")
  return string.rep("../", separators + 1)
end

--- @implNote a project's directory is its real one and its build file is named
--- from there back into the derived root, so nothing is written outside
--- `build/` (spec 7.1). Every module and implicit parent gets both lines: an
--- implicit parent left at its default directory would read whatever the root
--- link of that name holds, the user's own build file included.
local function append_real_tree_projects(lines, real_tree)
  for _, project in ipairs(real_tree.projects) do
    local path = groovy.quoted(build_file.gradle_path(project.name))
    lines[#lines + 1] = "project(" .. path .. ").projectDir = file("
                        .. groovy.quoted(real_tree.real_root .. "/" .. project.name) .. ")"
    lines[#lines + 1] = "project(" .. path .. ").buildFileName = "
                        .. groovy.quoted(climb_of(project.name) .. real_tree.derived .. "/"
                                         .. project.script)
  end
end

local function append_library_builds(lines, composite_record)
  if composite_record == nil then return end
  for _, build_name in ipairs(composite_record.library_builds) do
    lines[#lines + 1] = include_build_line(build_name)
  end
end

--- Without this Gradle names the project after its directory, which would be
--- "gradle".
---
--- @implNote one `include` per declared module, in manifest order. A nested
--- name includes its undeclared parents implicitly, as Gradle does, and daukle
--- writes no build file for them because they are not modules. An empty list
--- renders what a single-project build has always rendered, byte for byte.
--- @param applies_settings_plugins whether the manifest declares settings
--- plugins, which is all generate may know: their jars are acquired by a task
--- @param composite_record what `validation.composite_of` returns, or nil
--- @param real_tree nil for a build that carries no logic, else { root_script, classpath_file,
--- real_root = <the build's real root from the derived one>, derived = <the derived root from the
--- real one>, catalogs = <the list catalogs.checked returns>, projects = { { name, script } } }
function settings_file.settings(name, modules, applies_settings_plugins, composite_record,
                                real_tree)
  local wrapped = real_tree ~= nil and carried.is_kotlin(real_tree.settings_verbatim)
  local lines = { "// Generated by daukle/gradle. Do not edit." }
  if not wrapped then
    append_plugin_management(lines, composite_record)
    append_settings_classpath(lines, real_tree ~= nil and real_tree.classpath_file or nil)
    append_settings_plugins_block(lines, composite_record)
  end
  if applies_settings_plugins then
    lines[#lines + 1] = "apply from: " .. groovy.quoted(settings_file.SCRIPT)
  end
  if real_tree ~= nil then
    lines[#lines + 1] = "apply from: " .. groovy.quoted(carried.ROOT_LINKS)
  end
  append_library_builds(lines, composite_record)
  lines[#lines + 1] = "rootProject.name = " .. groovy.quoted(name)
  if real_tree ~= nil then
    lines[#lines + 1] = "rootProject.buildFileName = " .. groovy.quoted(real_tree.root_script)
    for _, line in ipairs(catalogs.settings_lines(real_tree.catalogs)) do
      lines[#lines + 1] = line
    end
  end
  if modules ~= nil and #modules > 0 then
    lines[#lines + 1] = ""
    for index = 1, #modules do
      lines[#lines + 1] = "include " .. groovy.quoted(build_file.gradle_path(modules[index].name))
    end
  end
  if real_tree ~= nil then append_real_tree_projects(lines, real_tree) end
  local text = table.concat(lines, "\n") .. "\n"
  if wrapped then return text end
  return text .. carried_settings_text(real_tree and real_tree.settings_verbatim)
end

--- @implNote every pinned id resolves to one module holding the whole pinned
--- classpath, rather than through a plugin marker: a marker's Maven path names
--- the id twice and passes Windows' 260-character limit in an ordinary
--- checkout. Measured on 8.13 and 9.6.0 with a settings extension accessor.
local function kotlin_plugin_management(pinned, composite_record)
  local plugin_builds = composite_record ~= nil and composite_record.plugin_builds or {}
  if #pinned == 0 and #plugin_builds == 0 then return "" end
  local lines = { "pluginManagement {" }
  if #pinned > 0 then
    lines[#lines + 1] = "  repositories { maven { url = uri("
                        .. build_file_kotlin.quoted(carried.SETTINGS_REPOSITORY) .. ") } }"
    lines[#lines + 1] = "  resolutionStrategy {"
    lines[#lines + 1] = "    eachPlugin {"
    for _, plugin in ipairs(pinned) do
      lines[#lines + 1] = "      if (requested.id.id == " .. build_file_kotlin.quoted(plugin.id) .. ") useModule("
                          .. build_file_kotlin.quoted(settings_file.CLASSPATH_MODULE) .. ")"
    end
    lines[#lines + 1] = "    }"
    lines[#lines + 1] = "  }"
  end
  for _, build_name in ipairs(plugin_builds) do
    lines[#lines + 1] = "  includeBuild(" .. build_file_kotlin.quoted(composite.path_of(build_name)) .. ")"
  end
  lines[#lines + 1] = "}"
  return table.concat(lines, "\n") .. "\n"
end

local function kotlin_settings_classpath(classpath_file)
  if classpath_file == nil then return "" end
  return "buildscript {\n  dependencies {\n    classpath(files(file(" .. build_file_kotlin.quoted(classpath_file)
         .. ").let { if (it.exists()) it.readLines().filter { line -> line.isNotEmpty() } else emptyList() }))\n"
         .. "  }\n}\n"
end

local function kotlin_plugins_block(pinned, owned_ids)
  if #pinned == 0 and #owned_ids == 0 then return "" end
  local lines = { "plugins {" }
  for _, plugin in ipairs(pinned) do
    lines[#lines + 1] = "  id(" .. build_file_kotlin.quoted(plugin.id) .. ") version "
                        .. build_file_kotlin.quoted(plugin.version)
  end
  for _, id in ipairs(owned_ids) do lines[#lines + 1] = "  id(" .. build_file_kotlin.quoted(id) .. ")" end
  lines[#lines + 1] = "}"
  return table.concat(lines, "\n") .. "\n"
end

--- The `settings.gradle.kts` of a build whose settings carry Kotlin: a
--- settings plugin's extension has a Kotlin accessor only in the settings
--- script whose own `plugins {}` resolved that plugin, so the carried text sits
--- here and the rest of the settings is the Groovy render it applies (spec
--- D-187, 4.3 and 7).
--- @param pinned the settings plugins with a version, resolved from the local repository
--- @param real_tree what `settings` takes, whose `settings_verbatim` holds Kotlin
function settings_file.kotlin_wrapper(composite_record, real_tree, pinned)
  local imports, rest = build_file_kotlin.split_imports(real_tree.settings_verbatim.text)
  if imports ~= "" and string.sub(imports, -1) ~= "\n" then imports = imports .. "\n" end
  local owned = composite_record ~= nil and composite_record.settings_ids or {}
  return "// Generated by daukle/gradle. Do not edit.\n" .. imports
         .. kotlin_plugin_management(pinned, composite_record)
         .. kotlin_settings_classpath(real_tree.classpath_file)
         .. kotlin_plugins_block(pinned, owned)
         .. "apply(from = " .. build_file_kotlin.quoted(carried.SETTINGS_RENDERED) .. ")\n\n"
         .. verbatim.warn_line(real_tree.settings_verbatim) .. "\n" .. rest
end

local REPOSITORY_GROUP = "daukle.settings"
local REPOSITORY_VERSION = "pinned"
local CLASSPATH_ARTIFACT = "classpath"
settings_file.CLASSPATH_MODULE = REPOSITORY_GROUP .. ":" .. CLASSPATH_ARTIFACT .. ":" .. REPOSITORY_VERSION

local function jar_artifact(index)
  return "jar" .. string.format("%d", index)
end

local function dependency_line(artifact)
  return "    <dependency><groupId>" .. REPOSITORY_GROUP .. "</groupId><artifactId>" .. artifact
         .. "</artifactId><version>" .. REPOSITORY_VERSION .. "</version></dependency>"
end

--- A module of the local repository: a jar's, or with `dependencies` the
--- POM-only module that is the whole classpath.
local function pom(artifact, dependencies)
  local lines = { "<project>", "  <modelVersion>4.0.0</modelVersion>",
                  "  <groupId>" .. REPOSITORY_GROUP .. "</groupId>", "  <artifactId>" .. artifact .. "</artifactId>",
                  "  <version>" .. REPOSITORY_VERSION .. "</version>" }
  if #dependencies > 0 then
    lines[#lines + 1] = "  <packaging>pom</packaging>"
    lines[#lines + 1] = "  <dependencies>"
    for _, dependency in ipairs(dependencies) do lines[#lines + 1] = dependency_line(dependency) end
    lines[#lines + 1] = "  </dependencies>"
  end
  lines[#lines + 1] = "</project>"
  return table.concat(lines, "\n") .. "\n"
end

--- A module's files, without their extension.
local function module_base(artifact)
  return carried.SETTINGS_REPOSITORY .. "/" .. string.gsub(REPOSITORY_GROUP, "%.", "/") .. "/" .. artifact .. "/"
         .. REPOSITORY_VERSION .. "/" .. artifact .. "-" .. REPOSITORY_VERSION
end

--- The local Maven repository the Kotlin wrapper resolves settings plugins
--- from: a POM per pinned jar, and the one module every pinned id resolves to,
--- depending on each jar; and the lines the init script copies each jar by,
--- `<target>\t<source>`, because a jar is not text and only Gradle can copy it.
--- @param jars the pinned jars' paths
--- @return { files = { { path, text } }, copies = <the copy list's text> }
function settings_file.settings_repository(jars)
  local files, copies, artifacts = {}, {}, {}
  for index, jar in ipairs(jars) do
    local artifact = jar_artifact(index)
    files[#files + 1] = { path = module_base(artifact) .. ".pom", text = pom(artifact, {}) }
    copies[#copies + 1] = module_base(artifact) .. ".jar\t" .. jar
    artifacts[#artifacts + 1] = artifact
  end
  files[#files + 1] = { path = module_base(CLASSPATH_ARTIFACT) .. ".pom", text = pom(CLASSPATH_ARTIFACT, artifacts) }
  return { files = files, copies = table.concat(copies, "\n") .. "\n" }
end

--- The init script every Gradle run of a Kotlin-wrapped build passes. It runs
--- before Gradle looks for a settings file, so it removes a `settings.gradle`
--- an earlier render left, which Gradle would read in the wrapper's place, and
--- copies the settings plugins' jars into the local repository.
---
--- @implNote measured on 7.6.4 and 9.6.0: with both settings files present
--- Gradle reads `settings.gradle` and says nothing. Only the main build runs
--- this, and the derived root never holds a user's file under either name.
settings_file.KOTLIN_SETTINGS_INIT = table.concat({
  "// Generated by daukle/gradle. Do not edit.",
  "import java.nio.file.Files",
  "import java.nio.file.StandardCopyOption",
  "",
  "if (gradle.parent == null) {",
  "  def daukleRoot = gradle.startParameter.projectDir ?: gradle.startParameter.currentDir",
  "  def daukleStale = new File(daukleRoot, 'settings.gradle')",
  "  if (daukleStale.isFile() && new File(daukleRoot, 'settings.gradle.kts').isFile()) daukleStale.delete()",
  "  def daukleCopies = new File(daukleRoot, " .. groovy.quoted(carried.SETTINGS_REPOSITORY_JARS) .. ")",
  "  if (daukleCopies.isFile()) {",
  "    daukleCopies.readLines().findAll { it }.each { line ->",
  "      def fields = line.split('\\t', 2)",
  "      def target = new File(daukleRoot, fields[0])",
  "      target.parentFile.mkdirs()",
  "      Files.copy(new File(fields[1]).toPath(), target.toPath(), StandardCopyOption.REPLACE_EXISTING)",
  "    }",
  "  }",
  "}",
}, "\n") .. "\n"

--- An included build's settings when its root carries logic: its links, and
--- the root's build file in that build's `build/scripts/`, and the catalogs it declares.
--- @param catalog_entries the list `catalogs.checked` returns
--- @param settings_verbatim what `verbatim.checked` returned for its `settingsVerbatim`, or nil
function settings_file.included_real_tree_settings(gradle_name, root_script, catalog_entries, settings_verbatim)
  local text = settings_file.included_settings(gradle_name)
               .. "apply from: " .. groovy.quoted(carried.ROOT_LINKS) .. "\n"
               .. "rootProject.buildFileName = " .. groovy.quoted(root_script) .. "\n"
  for _, line in ipairs(catalogs.settings_lines(catalog_entries)) do
    text = text .. line .. "\n"
  end
  return text .. carried_settings_text(settings_verbatim)
end

local function quoted_list(names)
  local quoted = {}
  for index = 1, #names do quoted[index] = groovy.quoted(names[index]) end
  return "[" .. table.concat(quoted, ", ") .. "]"
end

--- The script a carrying build's settings applies so that a root-relative path
--- reaches the real file: a link in the derived root to each entry of the real
--- one (spec 7.1).
---
--- @implNote a junction for a directory and a hard link for a file on Windows,
--- since neither needs a privilege and a symlink does; a symlink elsewhere; a
--- copy only where both are refused (D-57), since a write through a copy never
--- reaches the real file. An entry that is not the real one, such as a module
--- directory an earlier layout generated, is replaced, and the walk that
--- removes it deletes a link as the one node it is: a junction reports as a
--- directory with NOFOLLOW_LINKS, and descending into it would delete the
--- user's own files. A copy is reported, never silent.
--- @implNote mklink takes both paths from the child's environment, inside
--- quotes, because cmd parses `&`, `^` and `%` in an argument and Java quotes
--- an argument only for whitespace: a path like `D:\R&D` ran its tail as a
--- command and fell back to a copy without a word.
--- @implNote what was placed is recorded under the never-linked `build/`, so a
--- later render without logic can refuse to write through a hard link, which
--- no listing tells apart from a plain file. The record exists before the
--- first link does, so a run that dies while placing still leaves it. The
--- previous record is also what prunes an entry whose real one is gone: a hard
--- link or a copy outlives its real file, and only the record says it was ours.
--- @param real_directory the real directory, relative to the settings directory
function settings_file.root_links(real_directory)
  return table.concat({
    "// Generated by daukle/gradle. Do not edit.",
    "import java.nio.file.Files",
    "import java.nio.file.LinkOption",
    "import java.nio.file.Path",
    "",
    "def daukleDerived = settingsDir.toPath()",
    "def daukleReal = daukleDerived.resolve(" .. groovy.quoted(real_directory) .. ").normalize()",
    "def daukleUnlinked = " .. quoted_list(carried.UNLINKED) .. " as Set",
    "def daukleWindows = System.getProperty('os.name').toLowerCase().contains('windows')",
    "def daukleReparsePoint = 0x400",
    "",
    "def daukleIsLink = { Path path ->",
    "  Files.isSymbolicLink(path) || (daukleWindows && ((Files.getAttribute(path, 'dos:attributes',",
    "    LinkOption.NOFOLLOW_LINKS) as int) & daukleReparsePoint) != 0)",
    "}",
    "def daukleRemove",
    "daukleRemove = { Path path ->",
    "  if (!daukleIsLink(path) && Files.isDirectory(path, LinkOption.NOFOLLOW_LINKS)) {",
    "    path.toFile().listFiles().each { daukleRemove(it.toPath()) }",
    "  }",
    "  Files.delete(path)",
    "}",
    "def daukleCopy = { Path target, Path link ->",
    "  if (!Files.isDirectory(target)) {",
    "    Files.copy(target, link)",
    "    return",
    "  }",
    "  Files.walk(target).withCloseable { paths ->",
    "    paths.forEach { Path source ->",
    "      def destination = link.resolve(target.relativize(source).toString())",
    "      if (Files.isDirectory(source)) Files.createDirectories(destination)",
    "      else Files.copy(source, destination)",
    "    }",
    "  }",
    "}",
    "def daukleJunction = { Path target, Path link ->",
    "  def builder = new ProcessBuilder('cmd', '/c', 'mklink', '/J', '\"%DAUKLE_LINK%\"',",
    "    '\"%DAUKLE_TARGET%\"')",
    "  builder.environment().put('DAUKLE_LINK', link.toString())",
    "  builder.environment().put('DAUKLE_TARGET', target.toString())",
    "  builder.redirectErrorStream(true)",
    "  def process = builder.start()",
    "  process.inputStream.text",
    "  process.waitFor() == 0",
    "}",
    "def daukleHardLink = { Path target, Path link ->",
    "  try {",
    "    Files.createLink(link, target)",
    "    true",
    "  } catch (IOException ignored) {",
    "    false",
    "  }",
    "}",
    "def daukleSymbolicLink = { Path target, Path link ->",
    "  try {",
    "    Files.createSymbolicLink(link, link.parent.relativize(target))",
    "    true",
    "  } catch (IOException | UnsupportedOperationException ignored) {",
    "    false",
    "  }",
    "}",
    "def daukleLink = { Path target, Path link ->",
    "  def linked",
    "  if (!daukleWindows) linked = daukleSymbolicLink(target, link)",
    "  else if (Files.isDirectory(target)) linked = daukleJunction(target, link)",
    "  else linked = daukleHardLink(target, link)",
    "  if (linked) return 'link'",
    "  daukleCopy(target, link)",
    "  println \"daukle/gradle: linking ${target.fileName} was refused, so the derived root holds a\"",
    "    + ' copy, and a write to it does not reach the real file'",
    "  'copy'",
    "}",
    "def daukleIsPlaced = { Path link, Path target ->",
    "  Files.exists(link) && Files.isSameFile(link, target)",
    "}",
    "",
    "def daukleRecordFile = daukleDerived.resolve(" .. groovy.quoted(carried.LINK_RECORD) .. ")",
    "def daukleRecorded = !daukleRecordFile.toFile().isFile() ? [] : daukleRecordFile.toFile().readLines()",
    "  .findAll { it.startsWith('link ') || it.startsWith('copy ') }.collect { it.substring(5) }",
    "Files.createDirectories(daukleRecordFile.parent)",
    "daukleRecordFile.toFile().text = 'placing\\n'",
    "daukleDerived.toFile().listFiles().each { File entry ->",
    "  if (daukleIsLink(entry.toPath()) && !daukleReal.resolve(entry.name).toFile().exists()) {",
    "    Files.delete(entry.toPath())",
    "  }",
    "}",
    "daukleRecorded.each { String name ->",
    "  if (name in daukleUnlinked || name.contains('/') || name.contains('\\\\') || name in ['.', '..']) return",
    "  def placed = daukleDerived.resolve(name)",
    "  if (Files.exists(placed, LinkOption.NOFOLLOW_LINKS) && !daukleReal.resolve(name).toFile().exists()) {",
    "    daukleRemove(placed)",
    "  }",
    "}",
    "def daukleRecord = []",
    "daukleReal.toFile().listFiles().each { File entry ->",
    "  if (entry.name in daukleUnlinked || entry.name.startsWith("
      .. groovy.quoted(carried.MIGRATE_PREFIX) .. ")) return",
    "  def target = entry.toPath()",
    "  def link = daukleDerived.resolve(entry.name)",
    "  if (daukleIsPlaced(link, target)) {",
    "    daukleRecord << 'link ' + entry.name",
    "    return",
    "  }",
    "  if (Files.exists(link, LinkOption.NOFOLLOW_LINKS)) daukleRemove(link)",
    "  daukleRecord << daukleLink(target, link) + ' ' + entry.name",
    "}",
    "daukleRecordFile.toFile().text = daukleRecord.join('\\n') + '\\n'",
  }, "\n") .. "\n"
end

return settings_file
